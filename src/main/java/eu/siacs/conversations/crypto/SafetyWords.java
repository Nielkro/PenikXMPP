    public static List<String> compute(String inputA, String inputB, String context) {
        if (inputA == null) inputA = "";
        if (inputB == null) inputB = "";
        if (context == null) context = "";

        String[] parts = new String[] { inputA, inputB };
        Arrays.sort(parts);

        String combined = parts[0] + "|" + parts[1] + "|" + context;
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(combined.getBytes(StandardCharsets.UTF_8));
            List<String> words = new ArrayList<>(4);
            for (int i = 0; i < 4 && i < hash.length; i++) {
                int index = (hash[i] & 0xFF) % RUSSIAN_WORDS.length;
                words.add(RUSSIAN_WORDS[index]);
            }
            return words;
        } catch (NoSuchAlgorithmException e) {
            return Arrays.asList("алмаз", "волна", "маяк", "звезда");
        }
    }
